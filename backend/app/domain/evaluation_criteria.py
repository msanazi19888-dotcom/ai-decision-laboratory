from dataclasses import dataclass


@dataclass
class EvaluationCriteria:
    """
    Represents the business criteria used to
    evaluate replenishment strategies.
    """

    inventory_risk_weight: float = 0.40
    budget_weight: float = 0.20
    lead_time_weight: float = 0.20
    warehouse_capacity_weight: float = 0.10
    cost_weight: float = 0.10

    def total_weight(self) -> float:
        return (
            self.inventory_risk_weight
            + self.budget_weight
            + self.lead_time_weight
            + self.warehouse_capacity_weight
            + self.cost_weight
        )